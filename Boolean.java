class Boolean{
	
	public static void main(String[] args){
		
		//Initialization
			boolean isRaining=true,isSunny=false,isCreative=true,isWorking=false,isStudent=true;
			System.out.println("Boolean values:IsRaining="+isRaining+",IsSunny="+isSunny+",IsCreative="+isCreative+",IsWorking="+isWorking+",IsStudent="+isStudent);
			
		//Re-Initialization
			isRaining=false;
			isSunny=true;
			isCreative=false;
			isWorking=true;
			isStudent=false;
			System.out.println("Updated Boolean values:IsRaining="+isRaining+",IsSunny="+isSunny+",IsCreative="+isCreative+",IsWorking="+isWorking+",IsStudent="+isStudent);
	
	
	}
}