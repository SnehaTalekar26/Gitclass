class Char{
	
	public static void main(String[] args){
		
		//Initialization
			char grade='A',section='B',symbol='C',level='D',initial='E';
			System.out.println("char values:Grade="+grade+",Section="+section+",Symbol="+symbol+",Level="+level+",Initial="+initial);
			
		//Re-Initialization
			grade='B';
			section='C';
			symbol='X';
			level='C';
			initial='T';
			System.out.println("Updated Char values:Grade="+grade+",Section="+section+",Symbol="+symbol+",Level="+level+",Initial="+initial);
	
	
	}
}