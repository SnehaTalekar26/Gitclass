class Whiteboard{
	public static void writeon(String textin){
		System.out.println(textin);
	}
	public static void erase(String erasertype){
		System.out.println(erasertype);
	}
	public static void clean(String solution){
		System.out.println(solution);
	}
	public static void attachmagnet(float strength,String shapeon){
		System.out.println(strength+ "," +shapeon);
	}
	public static void setheight(float position,String mechanism){
		System.out.println(position+ "," +mechanism);
	}
	public static void drawchart(String typeof,float sizeof,String colorof){
		System.out.println(typeof+ "," +sizeof+ "," +colorof);
	}
	public static void projectdisplay(int brightness,String contrast,String resolution){
		System.out.println(brightness+ "," +contrast+ "," +resolution);
	}
}

